-- Исходная схема: таблица объявлений (сущность io.hexlet.project_devops_deploy.model.Bulletin)
CREATE TABLE bulletins (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(255)   NOT NULL,
    description TEXT           NOT NULL,
    state       VARCHAR(255)   NOT NULL CHECK (state IN ('DRAFT', 'PUBLISHED')),
    contact     VARCHAR(255)   NOT NULL,
    price       NUMERIC(12, 2) NOT NULL,
    image_key   VARCHAR(255),
    created_at  TIMESTAMP(6)   NOT NULL,
    updated_at  TIMESTAMP(6)   NOT NULL
);

CREATE INDEX bulletins_state_created_at_idx ON bulletins (state, created_at DESC);
